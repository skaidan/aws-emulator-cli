"""``awsemu compose``: a Docker Compose service for the emulator."""

from __future__ import annotations

import os
import platform
from pathlib import Path

import click
import yaml

from .. import project, runtime, ui
from ..context import Ctx, handle_errors, pass_ctx
from ..envvars import AUTH_OFF_KEYS
from ..paths import REGION, InstanceFiles, cli_root, emulator_root

CLIENT_ANCHOR = "aws-emulator-client"


def service(opts: runtime.StartOptions, system: str | None = None, arch: str | None = None, build: bool = True) -> dict:
    """The compose service, mirroring ``runtime.docker_command`` (the official recipe)."""
    system = system or platform.system()
    port = opts.port
    root = emulator_root()
    svc: dict = {"image": opts.image}
    if build:
        svc["build"] = {"context": ".", "dockerfile_inline": runtime.dockerfile(arch)}
    svc["command"] = runtime.emulator_args(opts)
    svc["ports"] = [f"127.0.0.1:{port}:{port}"]  # never expose it to the network
    svc["mem_limit"] = opts.memory
    svc["memswap_limit"] = opts.memory
    if system == "Windows":
        svc["volumes"] = [f"{root}:/home/emulator/.aws/emulator"]
    else:
        home = str(Path(os.path.expanduser("~")))
        svc["environment"] = {"HOME": home}
        svc["volumes"] = [f"{root}:{root}"]
        if system == "Linux" and hasattr(os, "getuid"):
            svc["user"] = f"{os.getuid()}:{os.getgid()}"
    return svc


def client_settings(port: int, proxy_port: int, auth: bool, system: str | None = None) -> dict:
    """What an app container needs to go through the proxy on the host."""
    system = system or platform.system()
    files = InstanceFiles(port)
    ca = cli_root() / "proxy" / "ca.pem"
    if system == "Windows":  # container paths can't be Windows paths
        ca_in, creds_dir = "/awsemu/proxy-ca.pem", "/awsemu/emulator"
        volumes = [f"{ca}:{ca_in}:ro", f"{files.dir}:{creds_dir}:ro"]
        creds = f"{creds_dir}/emulator_credentials"
    else:
        ca_in, creds = str(ca), str(files.credentials)
        # Only the certificate, never the CA's key next to it
        volumes = [f"{ca}:{ca}:ro", f"{files.dir}:{files.dir}:ro"]
    env = {
        "AWS_ENDPOINT_URL": f"https://host.docker.internal:{proxy_port}",
        "AWS_CA_BUNDLE": ca_in,
        "NODE_EXTRA_CA_CERTS": ca_in,
        "AWS_REGION": REGION,
        "AWS_DEFAULT_REGION": REGION,
        "AWS_EC2_METADATA_DISABLED": "true",
        "AWS_DISABLE_HOST_PREFIX_INJECTION": "true",
    }
    if auth:
        env["AWS_SHARED_CREDENTIALS_FILE"] = creds  # new keys on every start: read them, don't copy them
    else:
        env["AWS_ACCESS_KEY_ID"], env["AWS_SECRET_ACCESS_KEY"] = AUTH_OFF_KEYS
    return {"environment": env, "volumes": volumes, "extra_hosts": ["host.docker.internal:host-gateway"]}


def render(name: str, svc: dict, port: int, client: dict | None = None, proxy_port: int | None = None) -> str:
    class _Dumper(yaml.SafeDumper):
        pass

    def str_presenter(dumper, value):
        return dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|" if "\n" in value else None)

    _Dumper.add_representer(str, str_presenter)
    body = yaml.dump({"services": {name: svc}}, Dumper=_Dumper, sort_keys=False, width=100)
    if client is not None:
        block = yaml.dump({f"x-{CLIENT_ANCHOR}": client}, Dumper=_Dumper, sort_keys=False, width=100)
        block = block.replace(f"x-{CLIENT_ANCHOR}:", f"x-{CLIENT_ANCHOR}: &{CLIENT_ANCHOR}", 1)
        body = block + "\n" + body
    header = f"""\
# AWS Emulator as a Docker Compose service, generated by awsemu.
#
#   docker compose up -d {name}
#   awsemu --port {port} status        # wait until healthy
#   eval "$(awsemu --port {port} env)"  # point your tools at it
#
# The emulator writes its credentials and certificate to {emulator_root()}/{port}/
# on this machine (the volume below), so awsemu and your SDKs work from the host.
# The port is published on 127.0.0.1 only.
#
# Containers of your app: on Linux use `network_mode: host` and the variables from
# `awsemu env --shell dotenv`; mount {emulator_root()} at the same path so the
# certificate path in AWS_CA_BUNDLE resolves inside the container too.
"""
    if client is not None:
        header = (
            header.rsplit("# Containers of your app:", 1)[0]
            + f"""\
# Containers of your app go through the awsemu proxy on this machine (calls log,
# faults), at host.docker.internal:{proxy_port}. Start it so containers can reach it:
#
#   awsemu --port {port} proxy start -d --host 0.0.0.0
#
# and give each app service the settings below:
#
#   services:
#     app:
#       image: my-app
#       <<: *{CLIENT_ANCHOR}
#
# (A service's own `environment:` or `volumes:` replaces these instead of adding to
# them: copy the lines you need.) The credentials file is mounted, not copied: the
# emulator makes new keys on every start.
"""
        )
    return header + body


@click.command()
@click.option(
    "-o", "--output", type=click.Path(dir_okay=False, path_type=Path), help="Write to this file (default: stdout)."
)
@click.option("--name", default="aws-emulator", show_default=True, help="Service name.")
@click.option("--no-build", is_flag=True, help="Omit the build section (image built with 'awsemu image build').")
@click.option(
    "--auth/--no-auth",
    default=None,
    show_default="auth",
    help="Require SigV4-signed requests (default: awsemu.toml, else auth).",
)
@click.option(
    "--telemetry/--no-telemetry",
    default=None,
    help="Force telemetry on/off (default: awsemu.toml, else emulator settings).",
)
@click.option(
    "--idle-timeout",
    type=click.IntRange(1, 31536000),
    metavar="SECONDS",
    help="Stop after this many seconds without API calls.",
)
@click.option(
    "--proxy",
    "with_proxy",
    is_flag=True,
    help=f"Also write settings (x-{CLIENT_ANCHOR}) that send app containers through the awsemu proxy.",
)
@pass_ctx
@handle_errors
def compose(c: Ctx, output: Path | None, name: str, no_build: bool, auth, telemetry, idle_timeout, with_proxy):
    """Print a Docker Compose service for the emulator (same setup as 'start --docker').

    \b
      awsemu compose -o compose.emulator.yaml
      docker compose -f compose.emulator.yaml up -d
      awsemu compose --proxy -o compose.emulator.yaml   # app containers via the proxy
    """
    proj = project.load()

    def pick(flag, value, default):
        return flag if flag is not None else (value if value is not None else default)

    opts = runtime.StartOptions(
        port=c.port,
        mode="docker",
        auth=pick(auth, proj and proj.auth, True),
        telemetry=pick(telemetry, proj and proj.telemetry, None),
        idle_timeout=pick(idle_timeout, proj and proj.idle_timeout, None),
        image=(proj.image if proj and proj.image else runtime.DEFAULT_IMAGE),
        memory=(proj.memory if proj and proj.memory else "2g"),
    )
    client = proxy_port = None
    if with_proxy:
        from .proxy import default_listen

        proxy_port = default_listen(c.port) or c.port + 1
        client = client_settings(c.port, proxy_port, opts.auth)
    text = render(name, service(opts, build=not no_build), c.port, client, proxy_port)
    if output:
        output.write_text(text, encoding="utf-8")
        ui.success(f"wrote {output}")
        ui.echo(f"Next: docker compose -f {output} up -d {name}", "muted")
    else:
        click.echo(text, nl=False)
